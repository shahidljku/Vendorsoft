import { vi, describe, it, expect, beforeEach, afterEach } from 'vitest';
// Explicitly unmock firestore to test the real infrastructure implementation
vi.unmock('../../src/services/firestore');
import { getDocument } from '../../src/services/firestore';
import { RequestContext } from '../../src/services/logger';
import { Env } from '../../src/types';

describe('Infrastructure: Firestore Authentication Context Propagation', () => {
  let mockFetch: any;
  let mockCtx: RequestContext;
  let mockEnv: Env;
  let loggedErrors: any[];

  beforeEach(() => {
    loggedErrors = [];
    mockCtx = {
      traceId: 'test-trace',
      logger: {
        info: vi.fn(),
        debug: vi.fn(),
        warn: vi.fn(),
        error: vi.fn((msg, err) => {
          loggedErrors.push({ msg, err });
        })
      },
      telemetry: {
        measure: async (name: string, tags: any, fn: Function) => fn()
      }
    } as any;

    mockEnv = {
      FIRESTORE_SA_KEY: JSON.stringify({ client_email: 'test@gcp.com', private_key: 'bW9ja19rZXk=' }),
      GCP_PROJECT_ID: 'test-project'
    } as any;

    mockFetch = vi.fn().mockResolvedValue({
      ok: true,
      json: async () => ({ access_token: 'mock_token', expires_in: 3600 })
    });
    vi.stubGlobal('fetch', mockFetch);
    
    // Stub Web Crypto for JWT signing since we aren't testing real cryptography
    vi.stubGlobal('crypto', {
      subtle: {
        importKey: vi.fn().mockResolvedValue('mock_key'),
        sign: vi.fn().mockResolvedValue(new ArrayBuffer(8))
      }
    });
  });

  afterEach(() => {
    vi.unstubAllGlobals();
  });

  it('correctly propagates RequestContext to getFirestoreAccessToken without argument shifting', async () => {
    // If ctx is missing or shifted, env becomes ctx, and env.FIRESTORE_SA_KEY throws a TypeError
    // We intentionally mock fetch to return 404 for the actual document read so it exits cleanly after token generation
    mockFetch.mockResolvedValueOnce({
      ok: true,
      json: async () => ({ access_token: 'mock_token', expires_in: 3600 }) // Token Exchange
    }).mockResolvedValueOnce({
      ok: false,
      status: 404 // Document not found
    });

    const result = await getDocument(mockCtx, mockEnv, 'users', 'test_user');
    
    expect(result).toBeNull();
    if (loggedErrors.length > 0) console.log('LOGGED ERROR:', loggedErrors[0]);
    // The logger should have recorded NO errors. If it shifted arguments, it would throw or log a token error.
    expect(loggedErrors.length).toBe(0);

    // Verify fetch was called twice: once for token, once for document
    expect(mockFetch).toHaveBeenCalledTimes(2);
    
    // Verify the second fetch (document read) used the Bearer token generated by the first fetch
    const documentFetchArgs = mockFetch.mock.calls[1];
    expect(documentFetchArgs[1].headers['Authorization']).toBe('Bearer mock_token');
  });
});
