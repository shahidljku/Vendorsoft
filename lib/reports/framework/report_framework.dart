import 'dart:typed_data';
import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'report_config.dart';

/// The presentation engine for professional PDF reports.
/// This framework is strictly read-only and knows no domain logic.
class ReportFramework {
  
  /// Generates a complete professional PDF based on the provided configuration.
  static Future<Uint8List> generate(ReportConfig config) async {
    final pdf = pw.Document();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: config.pageFormat,
        margin: const pw.EdgeInsets.all(32),
        header: (context) => _buildHeader(context, config),
        footer: (context) => _buildFooter(context),
        build: (context) => _buildBody(context, config),
      ),
    );

    return pdf.save();
  }

  /// Builds the standard professional header with business details and page numbers.
  static pw.Widget _buildHeader(pw.Context context, ReportConfig config) {
    final now = DateTime.now();
    final dateStr = DateFormat('dd/MM/yyyy').format(now);
    final timeStr = DateFormat('hh:mm a').format(now);

    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.stretch,
      children: [
        pw.Text(
          config.businessName,
          style: pw.TextStyle(fontSize: 18, fontWeight: pw.FontWeight.bold),
          textAlign: pw.TextAlign.center,
        ),
        pw.SizedBox(height: 4),
        pw.Text(
          config.reportTitle,
          style: const pw.TextStyle(fontSize: 14),
          textAlign: pw.TextAlign.center,
        ),
        pw.Divider(thickness: 1.5),
        pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text('Generated: $dateStr at $timeStr', style: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold)),
                if (config.filters.isNotEmpty)
                  pw.Text('Filters: ${config.filters.join(', ')}', style: const pw.TextStyle(fontSize: 10)),
              ],
            ),
            pw.Text(
              'Page ${context.pageNumber} of ${context.pagesCount}',
              style: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold),
            ),
          ],
        ),
        pw.SizedBox(height: 12),
      ],
    );
  }

  /// Builds the standard footer with the generation timestamp.
  static pw.Widget _buildFooter(pw.Context context) {
    return pw.Container(
      alignment: pw.Alignment.centerRight,
      margin: const pw.EdgeInsets.only(top: 10),
      child: pw.Text(
        'Generated by VendSoft',
        style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600),
      ),
    );
  }

  /// Builds the core body of the report (Sections, Tables, and Totals).
  static List<pw.Widget> _buildBody(pw.Context context, ReportConfig config) {
    if (config.sections.isEmpty || config.sections.every((s) => s.rows.isEmpty)) {
      return [
        pw.SizedBox(height: 40),
        pw.Center(
          child: pw.Text(
            'No records found for the selected criteria.',
            style: pw.TextStyle(fontSize: 14, fontStyle: pw.FontStyle.italic),
          ),
        ),
      ];
    }

    List<pw.Widget> widgets = [];

    for (var section in config.sections) {
      if (section.rows.isEmpty) continue;

      if (section.title.isNotEmpty) {
        widgets.add(
          pw.Container(
            padding: const pw.EdgeInsets.symmetric(vertical: 6, horizontal: 8),
            color: PdfColors.grey200,
            width: double.infinity,
            child: pw.Text(
              section.title,
              style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 14),
            ),
          ),
        );
        widgets.add(pw.SizedBox(height: 8));
      }

      if (section.subtitle.isNotEmpty) {
        widgets.add(
          pw.Text(
            section.subtitle,
            style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 12),
          ),
        );
        widgets.add(pw.SizedBox(height: 6));
      }

      widgets.add(_buildTable(config, section.rows));

      if (section.summaryLines.isNotEmpty) {
        List<pw.Widget> summaryChildren = [];
        summaryChildren.add(pw.SizedBox(height: 6));
        for (var line in section.summaryLines) {
          summaryChildren.add(
            pw.Align(
              alignment: pw.Alignment.centerRight,
              child: pw.Text(
                line,
                style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 12),
              ),
            ),
          );
        }
        widgets.add(pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.stretch,
          mainAxisSize: pw.MainAxisSize.min,
          children: summaryChildren,
        ));
      }

      widgets.add(pw.SizedBox(height: 16));
    }

    if (config.grandTotals.isNotEmpty) {
      List<pw.Widget> grandTotalChildren = [];
      grandTotalChildren.add(pw.Divider(thickness: 2));
      grandTotalChildren.add(pw.SizedBox(height: 4));
      
      for (var i = 0; i < config.grandTotals.length; i++) {
        bool isLast = i == config.grandTotals.length - 1;
        grandTotalChildren.add(
          pw.Align(
            alignment: pw.Alignment.centerRight,
            child: pw.Text(
              config.grandTotals[i],
              style: pw.TextStyle(
                fontWeight: pw.FontWeight.bold,
                fontSize: isLast ? 14 : 12,
              ),
            ),
          ),
        );
      }
      
      grandTotalChildren.add(pw.SizedBox(height: 4));
      grandTotalChildren.add(pw.Divider(thickness: 2));

      widgets.add(pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.stretch,
        mainAxisSize: pw.MainAxisSize.min,
        children: grandTotalChildren,
      ));
    }

    return widgets;
  }

  /// Builds a repeating header table dynamically based on the config alignments.
  static pw.Widget _buildTable(ReportConfig config, List<List<String>> rows) {
    return pw.TableHelper.fromTextArray(
      headers: config.headers,
      data: rows,
      headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 11),
      cellStyle: const pw.TextStyle(fontSize: 10),
      headerDecoration: const pw.BoxDecoration(color: PdfColors.grey300),
      cellPadding: const pw.EdgeInsets.symmetric(vertical: 4, horizontal: 4),
      columnWidths: config.columnWidths,
      cellAlignments: config.columnAlignments,
      headerAlignments: config.columnAlignments, // Match headers to cell alignments
    );
  }
}
